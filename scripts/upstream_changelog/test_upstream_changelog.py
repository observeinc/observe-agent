class CollectTest(unittest.TestCase):
    def test_takes_every_release_after_old_up_to_new_and_filters_scope(self):
        changes = uc.collect({"core": "0.149.0", "contrib": "0.149.0"},
                             {"core": "0.151.0", "contrib": "0.151.0"},
                             gomod("0.151.0", "0.151.0"), fake_fetch())
        self.assertEqual(changes["releases"], {"core": ["0.150.0", "0.151.0"], "contrib": ["0.150.0", "0.151.0"]})
        # Out of scope: 512 (component we don't build), 70 (cmd/mdatagen), 78 (cmd/builder).
        self.assertEqual(sorted(e["prs"][0] for e in changes["entries"]), ["500", "501", "510", "513", "77"])
        self.assertEqual(changes["total"], 8)

    def test_fetches_only_repos_whose_version_changed(self):
        calls = []
        changes = uc.collect({"core": "0.151.0", "contrib": "0.150.0"},
                             {"core": "0.151.0", "contrib": "0.151.0"},
                             gomod("0.151.0", "0.151.0"), fake_fetch(calls))
        self.assertEqual(calls, [("contrib", "0.151.0")])
        self.assertEqual(changes["releases"], {"core": [], "contrib": ["0.151.0"]})

    def test_missing_target_section_fails(self):
        with self.assertRaisesRegex(SystemExit, "v0.153.0"):
            uc.collect({"core": "0.151.0", "contrib": "0.151.0"},
                       {"core": "0.151.0", "contrib": "0.153.0"},
                       gomod("0.151.0", "0.153.0"), fake_fetch())


class RenderTest(unittest.TestCase):
    def setUp(self):
        self.old = {"core": "0.149.0", "contrib": "0.149.0"}
        self.new = {"core": "0.151.0", "contrib": "0.151.0"}
        self.changes = uc.collect(self.old, self.new, gomod("0.151.0", "0.151.0"), fake_fetch())

    def test_unchanged_versions_say_so(self):
        out = uc.render(self.new, self.new, {"releases": {"core": [], "contrib": []}, "entries": [], "total": 0}, "v2.19.0")
        self.assertIn("still based on OpenTelemetry Collector v0.151.0", out)
        self.assertIn("v2.19.0", out)
        self.assertNotIn("<details>", out)

    def test_intro_links_every_upstream_release_and_reports_scope(self):
        out = uc.render(self.old, self.new, self.changes, "v2.15.0")
        self.assertIn("from v0.149.0 to v0.151.0", out)
        self.assertIn("[v0.150.0](https://github.com/open-telemetry/opentelemetry-collector/releases/tag/v0.150.0)", out)
        self.assertIn("[v0.151.0](https://github.com/open-telemetry/opentelemetry-collector-contrib/releases/tag/v0.151.0)", out)
        self.assertIn("5 of 8 upstream entries", out)

    def test_categories_are_ordered_and_folded(self):
        out = uc.render(self.old, self.new, self.changes, "v2.15.0")
        headings = [l for l in out.splitlines() if l.startswith("### ")]
        self.assertEqual(headings, ["### 🛑 Breaking changes 🛑", "### 🚩 Deprecations 🚩", "### 💡 Enhancements 💡",
                                    "### 🧰 Bug fixes 🧰", "### Known Issues"])
        self.assertEqual(out.count("<details>"), 5)
        self.assertIn("<summary>1 change</summary>\n\n- (Contrib v0.151.0)", out)

    def test_entries_are_prefixed_linked_and_keep_their_body(self):
        out = uc.render(self.old, self.new, self.changes, "v2.15.0")
        issues = "https://github.com/open-telemetry/opentelemetry-collector-contrib/issues"
        self.assertIn(f"- (Contrib v0.151.0) `receiver/file_log`: Rename a setting. ([#510]({issues}/510), [#511]({issues}/511))\n"
                      "  Use `new_name` instead.\n"
                      "    - nested detail\n", out)
        self.assertIn("- (Core v0.151.0) `exporter/otlp_http`: Deprecate a field. "
                      "([#77](https://github.com/open-telemetry/opentelemetry-collector/issues/77))", out)

    def test_core_entries_come_before_contrib_in_a_category(self):
        changes = dict(self.changes, entries=[
            dict(repo="contrib", ver="0.150.0", heading="Bug fixes", tags=["pkg/ottl"], title="b", body=""),
            dict(repo="core", ver="0.151.0", heading="Bug fixes", tags=["pkg/service"], title="a", body=""),
        ])
        out = uc.render(self.old, self.new, changes, "v2.15.0")
        self.assertLess(out.index("(Core v0.151.0)"), out.index("(Contrib v0.150.0)"))

    def test_over_budget_drops_non_breaking_bodies_first(self):
        groups = uc.group_entries(self.changes["entries"])
        budget = len(uc.render_sections(self.old, self.new, self.changes, groups, False, {}))
        self.assertGreater(len(uc.render(self.old, self.new, self.changes, "v2.15.0")), budget)
        out = uc.render(self.old, self.new, self.changes, "v2.15.0", budget=budget)
        self.assertNotIn("Leak detail.", out)
        self.assertIn("Fix a leak.", out)
        self.assertIn("Use `new_name` instead.", out)
        self.assertIn("left out the details of non-breaking entries", out)
        self.assertNotIn("more in the upstream release notes", out)

    def test_far_over_budget_truncates_but_keeps_breaking_changes(self):
        groups = uc.group_entries(self.changes["entries"])
        budget = len(uc.render_sections(self.old, self.new, self.changes, groups, False,
                                        {"Known Issues": 1, "Bug fixes": 1}))
        out = uc.render(self.old, self.new, self.changes, "v2.15.0", budget=budget)
        self.assertLessEqual(len(out), budget)
        self.assertIn("Rename a setting.", out)
        self.assertIn("Use `new_name` instead.", out)
        self.assertIn("Deprecate a field.", out)
        self.assertNotIn("Something to watch.", out)
        self.assertNotIn("Fix a leak.", out)
        self.assertIn("1 more in the upstream release notes", out)


class SpliceTest(unittest.TestCase):
    def test_appends_when_absent_and_replaces_when_present(self):
        once = uc.splice("## Changelog\n* fix\n", "first")
        self.assertTrue(once.startswith("## Changelog\n* fix\n\n"))
        self.assertIn(f"{uc.MARK_START}\nfirst\n{uc.MARK_END}", once)
        twice = uc.splice(once, "second")
        self.assertNotIn("first", twice)
        self.assertEqual(twice.count(uc.MARK_START), 1)
        self.assertTrue(twice.startswith("## Changelog\n* fix\n\n"))


class UpdateReleaseTest(unittest.TestCase):
    def test_rewrites_the_release_body_within_githubs_limit(self):
        release = {"body": "## Changelog\n* fix\n"}
        budgets = []

        def fake_run(*args, stdin=None):
            if args[:3] == ("gh", "release", "view"):
                return release["body"] + "\n"
            if args[:3] == ("gh", "release", "edit"):
                self.assertEqual(args[3:], ("v2.20.0", "--notes-file", "-"))
                release["body"] = stdin
                return ""
            raise AssertionError(f"unexpected command {args}")

        def render(budget):
            budgets.append(budget)
            return f"section {len(budgets)}"

        with mock.patch.object(uc, "run", fake_run):
            uc.update_release("v2.20.0", render)
            uc.update_release("v2.20.0", render)
        self.assertEqual(release["body"].count(uc.MARK_START), 1)
        self.assertIn("section 2", release["body"])
        self.assertNotIn("section 1", release["body"])
        self.assertTrue(release["body"].startswith("## Changelog\n* fix\n\n"))
        self.assertEqual(budgets[0], uc.MAX_CHARS)

    def test_budget_shrinks_when_goreleasers_notes_are_long(self):
        long_notes = "x" * 50_000
        budgets = []
        with mock.patch.object(uc, "run", lambda *a, stdin=None: long_notes if a[2] == "view" else ""):
            uc.update_release("v2.20.0", lambda budget: budgets.append(budget) or "s")
        self.assertLess(budgets[0], uc.GITHUB_BODY_LIMIT - 50_000)


